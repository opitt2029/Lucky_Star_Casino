APPENDIX_PREFIX = "【附錄頁・主線跳過】"


def inject(src: str, dest: str) -> None:
    prs = Presentation(src)
    total = len(prs.slides)
    written, skipped = 0, 0

    for idx, slide in enumerate(prs.slides, start=1):
        text = NOTES.get(idx)
        if text is None and idx in APPENDIX_HINT:
            # 附錄頁只加一行提示，並保留原本備忘稿（可能有原作者寫的東西）
            original = ""
            if slide.has_notes_slide:
                original = slide.notes_slide.notes_text_frame.text.strip()
            hint = f"{APPENDIX_PREFIX} {APPENDIX_HINT[idx]}"
            text = f"{hint}\n\n{original}" if original else hint

        if text is None:
            skipped += 1
            continue

        # 存取 notes_slide 這個 property 會在該頁沒有備忘稿時自動建立一份
        slide.notes_slide.notes_text_frame.text = text
        written += 1

    prs.save(dest)
    print(f"總頁數 {total}｜寫入 {written} 頁｜略過 {skipped} 頁")
    print(f"輸出：{dest}")


